    LONGITUD_ORIGEN DECIMAL(11, 8) NOT NULL,
    LATITUD_DESTINO DECIMAL(11, 8) NOT NULL,
    LONGITUD_DESTINO DECIMAL(11, 8) NOT NULL,
    FECHA_INICIO_SOLICITUD DATE NOT NULL,
    FECHA_FIN_SOLICITUD DATE,
    COSTO_ESTIMADO DECIMAL(10, 2),
    COSTO_REAL DECIMAL(10, 2),
    TIEMPO_ESTIMADO INT,
    TIEMPO_REAL INT,
    ID_ESTADO_SOLICITUD BIGINT NOT NULL,
    ID_CONTENEDOR BIGINT NOT NULL,
    NRO_DOCUMENTO_CLIENTE VARCHAR(20) NOT NULL,
    ID_TIPO_DOCUMENTO_CLIENTE BIGINT NOT NULL,
    CONSTRAINT FK_SOLICITUDES_CIUDAD_ORIGEN FOREIGN KEY (ID_CIUDAD_ORIGEN)
        REFERENCES CIUDADES(ID_CIUDAD),
    CONSTRAINT FK_SOLICITUDES_CIUDAD_DESTINO FOREIGN KEY (ID_CIUDAD_DESTINO)
        REFERENCES CIUDADES(ID_CIUDAD),
    CONSTRAINT FK_SOLICITUDES_ESTADO FOREIGN KEY (ID_ESTADO_SOLICITUD)
        REFERENCES ESTADOS_SOLICITUDES(ID_ESTADO_SOLICITUD),
    CONSTRAINT FK_SOLICITUDES_CONTENEDOR FOREIGN KEY (ID_CONTENEDOR)
        REFERENCES CONTENEDORES(ID_CONTENEDOR),
    CONSTRAINT FK_SOLICITUDES_CLIENTE FOREIGN KEY (NRO_DOCUMENTO_CLIENTE, ID_TIPO_DOCUMENTO_CLIENTE)
        REFERENCES CLIENTES(NRO_DOCUMENTO, ID_TIPO_DOCUMENTO)
