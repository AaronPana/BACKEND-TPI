-- Tabla: SOLICITUDES
CREATE TABLE SOLICITUDES (
    NRO_SOLICITUD IDENTITY PRIMARY KEY,
    DIRECCION_ORIGEN VARCHAR(200),
    DIRECCION_DESTINO VARCHAR(200),
    ID_CIUDAD_ORIGEN BIGINT NOT NULL,
    ID_CIUDAD_DESTINO BIGINT NOT NULL,
