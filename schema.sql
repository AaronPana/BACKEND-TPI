    CONSTRAINT FK_CAMIONES_TRANSPORTISTA FOREIGN KEY (NRO_DOCUMENTO_TRANSPORTISTA, ID_TIPO_DOCUMENTO_TRANSPORTISTA)
        REFERENCES TRANSPORTISTAS(NRO_DOCUMENTO, ID_TIPO_DOCUMENTO)
